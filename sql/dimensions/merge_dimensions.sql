MERGE INTO {{database}}.{{analytics_schema}}.DIM_AIRLINE TARGET
USING (
  SELECT AIRLINE_CODE, MAX(AIRLINE_DOT_ID) AS AIRLINE_DOT_ID,
         MIN(FLIGHT_DATE) AS FIRST_SEEN_DATE, MAX(FLIGHT_DATE) AS LAST_SEEN_DATE
  FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN
  WHERE SOURCE_MONTH = TO_DATE('{{source_month}}')
  GROUP BY AIRLINE_CODE
) SOURCE
ON TARGET.AIRLINE_CODE = SOURCE.AIRLINE_CODE
WHEN MATCHED THEN UPDATE SET
  AIRLINE_DOT_ID = COALESCE(SOURCE.AIRLINE_DOT_ID, TARGET.AIRLINE_DOT_ID),
  FIRST_SEEN_DATE = LEAST(TARGET.FIRST_SEEN_DATE, SOURCE.FIRST_SEEN_DATE),
  LAST_SEEN_DATE = GREATEST(TARGET.LAST_SEEN_DATE, SOURCE.LAST_SEEN_DATE),
  UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
  (AIRLINE_CODE, AIRLINE_DOT_ID, FIRST_SEEN_DATE, LAST_SEEN_DATE)
VALUES
  (SOURCE.AIRLINE_CODE, SOURCE.AIRLINE_DOT_ID, SOURCE.FIRST_SEEN_DATE, SOURCE.LAST_SEEN_DATE);

MERGE INTO {{database}}.{{analytics_schema}}.DIM_AIRPORT TARGET
USING (
  SELECT AIRPORT_ID, MAX_BY(AIRPORT_CODE, FLIGHT_DATE) AS AIRPORT_CODE,
         MAX_BY(CITY_NAME, FLIGHT_DATE) AS CITY_NAME,
         MAX_BY(STATE_CODE, FLIGHT_DATE) AS STATE_CODE,
         MIN(FLIGHT_DATE) AS FIRST_SEEN_DATE, MAX(FLIGHT_DATE) AS LAST_SEEN_DATE
  FROM (
    SELECT ORIGIN_AIRPORT_ID AS AIRPORT_ID, ORIGIN_CODE AS AIRPORT_CODE,
           ORIGIN_CITY AS CITY_NAME, ORIGIN_STATE AS STATE_CODE, FLIGHT_DATE
    FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN
    WHERE SOURCE_MONTH = TO_DATE('{{source_month}}')
    UNION ALL
    SELECT DESTINATION_AIRPORT_ID, DESTINATION_CODE, DESTINATION_CITY,
           DESTINATION_STATE, FLIGHT_DATE
    FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN
    WHERE SOURCE_MONTH = TO_DATE('{{source_month}}')
  )
  GROUP BY AIRPORT_ID
) SOURCE
ON TARGET.AIRPORT_ID = SOURCE.AIRPORT_ID
WHEN MATCHED THEN UPDATE SET
  AIRPORT_CODE = SOURCE.AIRPORT_CODE,
  CITY_NAME = SOURCE.CITY_NAME,
  STATE_CODE = SOURCE.STATE_CODE,
  FIRST_SEEN_DATE = LEAST(TARGET.FIRST_SEEN_DATE, SOURCE.FIRST_SEEN_DATE),
  LAST_SEEN_DATE = GREATEST(TARGET.LAST_SEEN_DATE, SOURCE.LAST_SEEN_DATE),
  UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT
  (AIRPORT_ID, AIRPORT_CODE, CITY_NAME, STATE_CODE, FIRST_SEEN_DATE, LAST_SEEN_DATE)
VALUES
  (SOURCE.AIRPORT_ID, SOURCE.AIRPORT_CODE, SOURCE.CITY_NAME, SOURCE.STATE_CODE,
   SOURCE.FIRST_SEEN_DATE, SOURCE.LAST_SEEN_DATE);

MERGE INTO {{database}}.{{analytics_schema}}.DIM_DATE TARGET
USING (
  SELECT DISTINCT
    TO_NUMBER(TO_CHAR(FLIGHT_DATE, 'YYYYMMDD')) AS DATE_KEY,
    FLIGHT_DATE AS CALENDAR_DATE,
    YEAR(FLIGHT_DATE) AS CALENDAR_YEAR,
    QUARTER(FLIGHT_DATE) AS CALENDAR_QUARTER,
    MONTH(FLIGHT_DATE) AS CALENDAR_MONTH,
    MONTHNAME(FLIGHT_DATE) AS MONTH_NAME,
    DAY(FLIGHT_DATE) AS DAY_OF_MONTH,
    DAYOFWEEKISO(FLIGHT_DATE) AS DAY_OF_WEEK,
    DAYNAME(FLIGHT_DATE) AS DAY_NAME,
    DAYOFWEEKISO(FLIGHT_DATE) IN (6, 7) AS IS_WEEKEND,
    TO_CHAR(FLIGHT_DATE, 'YYYY-MM') AS YEAR_MONTH
  FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN
  WHERE SOURCE_MONTH = TO_DATE('{{source_month}}')
) SOURCE
ON TARGET.DATE_KEY = SOURCE.DATE_KEY
WHEN NOT MATCHED THEN INSERT
  (DATE_KEY, CALENDAR_DATE, CALENDAR_YEAR, CALENDAR_QUARTER, CALENDAR_MONTH,
   MONTH_NAME, DAY_OF_MONTH, DAY_OF_WEEK, DAY_NAME, IS_WEEKEND, YEAR_MONTH)
VALUES
  (SOURCE.DATE_KEY, SOURCE.CALENDAR_DATE, SOURCE.CALENDAR_YEAR,
   SOURCE.CALENDAR_QUARTER, SOURCE.CALENDAR_MONTH, SOURCE.MONTH_NAME,
   SOURCE.DAY_OF_MONTH, SOURCE.DAY_OF_WEEK, SOURCE.DAY_NAME,
   SOURCE.IS_WEEKEND, SOURCE.YEAR_MONTH);

