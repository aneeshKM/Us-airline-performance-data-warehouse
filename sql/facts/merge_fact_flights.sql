BEGIN;

DELETE FROM {{database}}.{{analytics_schema}}.FACT_FLIGHTS TARGET
WHERE TARGET.SOURCE_MONTH = TO_DATE('{{source_month}}')
  AND NOT EXISTS (
    SELECT 1
    FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN SOURCE
    WHERE SOURCE.SOURCE_MONTH = TO_DATE('{{source_month}}')
      AND SOURCE.FLIGHT_ID = TARGET.FLIGHT_KEY
  );

MERGE INTO {{database}}.{{analytics_schema}}.FACT_FLIGHTS TARGET
USING (
  SELECT
    S.FLIGHT_ID AS FLIGHT_KEY,
    TO_NUMBER(TO_CHAR(S.FLIGHT_DATE, 'YYYYMMDD')) AS DATE_KEY,
    A.AIRLINE_KEY,
    O.AIRPORT_KEY AS ORIGIN_AIRPORT_KEY,
    D.AIRPORT_KEY AS DESTINATION_AIRPORT_KEY,
    S.* EXCLUDE (FLIGHT_ID)
  FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN S
  JOIN {{database}}.{{analytics_schema}}.DIM_AIRLINE A
    ON A.AIRLINE_CODE = S.AIRLINE_CODE
  JOIN {{database}}.{{analytics_schema}}.DIM_AIRPORT O
    ON O.AIRPORT_ID = S.ORIGIN_AIRPORT_ID
  JOIN {{database}}.{{analytics_schema}}.DIM_AIRPORT D
    ON D.AIRPORT_ID = S.DESTINATION_AIRPORT_ID
  WHERE S.SOURCE_MONTH = TO_DATE('{{source_month}}')
) SOURCE
ON TARGET.FLIGHT_KEY = SOURCE.FLIGHT_KEY
WHEN MATCHED THEN UPDATE SET
  DATE_KEY = SOURCE.DATE_KEY,
  AIRLINE_KEY = SOURCE.AIRLINE_KEY,
  ORIGIN_AIRPORT_KEY = SOURCE.ORIGIN_AIRPORT_KEY,
  DESTINATION_AIRPORT_KEY = SOURCE.DESTINATION_AIRPORT_KEY,
  SOURCE_MONTH = SOURCE.SOURCE_MONTH,
  FLIGHT_NUMBER = SOURCE.FLIGHT_NUMBER,
  TAIL_NUMBER = SOURCE.TAIL_NUMBER,
  SCHEDULED_DEPARTURE = SOURCE.SCHEDULED_DEPARTURE,
  ACTUAL_DEPARTURE = SOURCE.ACTUAL_DEPARTURE,
  SCHEDULED_ARRIVAL = SOURCE.SCHEDULED_ARRIVAL,
  ACTUAL_ARRIVAL = SOURCE.ACTUAL_ARRIVAL,
  DEPARTURE_DELAY_MINUTES = SOURCE.DEPARTURE_DELAY_MINUTES,
  ARRIVAL_DELAY_MINUTES = SOURCE.ARRIVAL_DELAY_MINUTES,
  SCHEDULED_ELAPSED_MINUTES = SOURCE.SCHEDULED_ELAPSED_MINUTES,
  ACTUAL_ELAPSED_MINUTES = SOURCE.ACTUAL_ELAPSED_MINUTES,
  AIR_TIME_MINUTES = SOURCE.AIR_TIME_MINUTES,
  DISTANCE_MILES = SOURCE.DISTANCE_MILES,
  CANCELLED_FLAG = SOURCE.CANCELLED_FLAG,
  DIVERTED_FLAG = SOURCE.DIVERTED_FLAG,
  ON_TIME_FLAG = SOURCE.ON_TIME_FLAG,
  DELAY_CATEGORY = SOURCE.DELAY_CATEGORY,
  CARRIER_DELAY_MINUTES = SOURCE.CARRIER_DELAY_MINUTES,
  WEATHER_DELAY_MINUTES = SOURCE.WEATHER_DELAY_MINUTES,
  NAS_DELAY_MINUTES = SOURCE.NAS_DELAY_MINUTES,
  SECURITY_DELAY_MINUTES = SOURCE.SECURITY_DELAY_MINUTES,
  LATE_AIRCRAFT_DELAY_MINUTES = SOURCE.LATE_AIRCRAFT_DELAY_MINUTES,
  SOURCE_FILE = SOURCE.SOURCE_FILE,
  PIPELINE_RUN_ID = SOURCE.PIPELINE_RUN_ID,
  UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  FLIGHT_KEY, DATE_KEY, AIRLINE_KEY, ORIGIN_AIRPORT_KEY, DESTINATION_AIRPORT_KEY,
  SOURCE_MONTH, FLIGHT_NUMBER, TAIL_NUMBER,
  SCHEDULED_DEPARTURE, ACTUAL_DEPARTURE, SCHEDULED_ARRIVAL, ACTUAL_ARRIVAL,
  DEPARTURE_DELAY_MINUTES, ARRIVAL_DELAY_MINUTES,
  SCHEDULED_ELAPSED_MINUTES, ACTUAL_ELAPSED_MINUTES, AIR_TIME_MINUTES,
  DISTANCE_MILES, CANCELLED_FLAG, DIVERTED_FLAG, ON_TIME_FLAG, DELAY_CATEGORY,
  CARRIER_DELAY_MINUTES, WEATHER_DELAY_MINUTES, NAS_DELAY_MINUTES,
  SECURITY_DELAY_MINUTES, LATE_AIRCRAFT_DELAY_MINUTES,
  SOURCE_FILE, PIPELINE_RUN_ID
) VALUES (
  SOURCE.FLIGHT_KEY, SOURCE.DATE_KEY, SOURCE.AIRLINE_KEY,
  SOURCE.ORIGIN_AIRPORT_KEY, SOURCE.DESTINATION_AIRPORT_KEY,
  SOURCE.SOURCE_MONTH, SOURCE.FLIGHT_NUMBER, SOURCE.TAIL_NUMBER,
  SOURCE.SCHEDULED_DEPARTURE, SOURCE.ACTUAL_DEPARTURE,
  SOURCE.SCHEDULED_ARRIVAL, SOURCE.ACTUAL_ARRIVAL,
  SOURCE.DEPARTURE_DELAY_MINUTES, SOURCE.ARRIVAL_DELAY_MINUTES,
  SOURCE.SCHEDULED_ELAPSED_MINUTES, SOURCE.ACTUAL_ELAPSED_MINUTES,
  SOURCE.AIR_TIME_MINUTES, SOURCE.DISTANCE_MILES,
  SOURCE.CANCELLED_FLAG, SOURCE.DIVERTED_FLAG, SOURCE.ON_TIME_FLAG,
  SOURCE.DELAY_CATEGORY, SOURCE.CARRIER_DELAY_MINUTES,
  SOURCE.WEATHER_DELAY_MINUTES, SOURCE.NAS_DELAY_MINUTES,
  SOURCE.SECURITY_DELAY_MINUTES, SOURCE.LATE_AIRCRAFT_DELAY_MINUTES,
  SOURCE.SOURCE_FILE, SOURCE.PIPELINE_RUN_ID
);

COMMIT;
