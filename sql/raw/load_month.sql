USE SCHEMA {{database}}.{{raw_schema}};

CREATE OR REPLACE TEMPORARY TABLE BTS_MONTH_BUFFER (
  YEAR VARCHAR,
  QUARTER VARCHAR,
  MONTH VARCHAR,
  DAYOFMONTH VARCHAR,
  DAYOFWEEK VARCHAR,
  FLIGHTDATE VARCHAR,
  REPORTING_AIRLINE VARCHAR,
  DOT_ID_REPORTING_AIRLINE VARCHAR,
  IATA_CODE_REPORTING_AIRLINE VARCHAR,
  TAIL_NUMBER VARCHAR,
  FLIGHT_NUMBER_REPORTING_AIRLINE VARCHAR,
  ORIGINAIRPORTID VARCHAR,
  ORIGIN VARCHAR,
  ORIGINCITYNAME VARCHAR,
  ORIGINSTATE VARCHAR,
  DESTAIRPORTID VARCHAR,
  DEST VARCHAR,
  DESTCITYNAME VARCHAR,
  DESTSTATE VARCHAR,
  CRSDEPTIME VARCHAR,
  DEPTIME VARCHAR,
  DEPDELAY VARCHAR,
  CRSARRTIME VARCHAR,
  ARRTIME VARCHAR,
  ARRDELAY VARCHAR,
  CANCELLED VARCHAR,
  CANCELLATIONCODE VARCHAR,
  DIVERTED VARCHAR,
  CRSELAPSEDTIME VARCHAR,
  ACTUALELAPSEDTIME VARCHAR,
  AIRTIME VARCHAR,
  FLIGHTS VARCHAR,
  DISTANCE VARCHAR,
  CARRIERDELAY VARCHAR,
  WEATHERDELAY VARCHAR,
  NASDELAY VARCHAR,
  SECURITYDELAY VARCHAR,
  LATEAIRCRAFTDELAY VARCHAR
);

COPY INTO BTS_MONTH_BUFFER
FROM @{{database}}.{{raw_schema}}.{{stage}}/{{stage_prefix}}/
FILES = ('{{source_file}}')
FILE_FORMAT = (FORMAT_NAME = '{{database}}.{{raw_schema}}.BTS_CSV_WITH_HEADER')
MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE
ON_ERROR = ABORT_STATEMENT
FORCE = TRUE;

BEGIN;

DELETE FROM {{database}}.{{raw_schema}}.FLIGHTS
WHERE SOURCE_MONTH = TO_DATE('{{source_month}}-01', 'YYYY-MM-DD');

INSERT INTO {{database}}.{{raw_schema}}.FLIGHTS (
  YEAR, QUARTER, MONTH, DAYOFMONTH, DAYOFWEEK, FLIGHTDATE,
  REPORTING_AIRLINE, DOT_ID_REPORTING_AIRLINE, IATA_CODE_REPORTING_AIRLINE,
  TAIL_NUMBER, FLIGHT_NUMBER_REPORTING_AIRLINE,
  ORIGINAIRPORTID, ORIGIN, ORIGINCITYNAME, ORIGINSTATE,
  DESTAIRPORTID, DEST, DESTCITYNAME, DESTSTATE,
  CRSDEPTIME, DEPTIME, DEPDELAY, CRSARRTIME, ARRTIME, ARRDELAY,
  CANCELLED, CANCELLATIONCODE, DIVERTED,
  CRSELAPSEDTIME, ACTUALELAPSEDTIME, AIRTIME, FLIGHTS, DISTANCE,
  CARRIERDELAY, WEATHERDELAY, NASDELAY, SECURITYDELAY, LATEAIRCRAFTDELAY,
  SOURCE_MONTH, SOURCE_FILE, SOURCE_FILE_CHECKSUM, SOURCE_ROW_NUMBER,
  SOURCE_RECORD_HASH, PIPELINE_RUN_ID
)
SELECT
  YEAR, QUARTER, MONTH, DAYOFMONTH, DAYOFWEEK, FLIGHTDATE,
  REPORTING_AIRLINE, DOT_ID_REPORTING_AIRLINE, IATA_CODE_REPORTING_AIRLINE,
  TAIL_NUMBER, FLIGHT_NUMBER_REPORTING_AIRLINE,
  ORIGINAIRPORTID, ORIGIN, ORIGINCITYNAME, ORIGINSTATE,
  DESTAIRPORTID, DEST, DESTCITYNAME, DESTSTATE,
  CRSDEPTIME, DEPTIME, DEPDELAY, CRSARRTIME, ARRTIME, ARRDELAY,
  CANCELLED, CANCELLATIONCODE, DIVERTED,
  CRSELAPSEDTIME, ACTUALELAPSEDTIME, AIRTIME, FLIGHTS, DISTANCE,
  CARRIERDELAY, WEATHERDELAY, NASDELAY, SECURITYDELAY, LATEAIRCRAFTDELAY,
  TO_DATE('{{source_month}}-01', 'YYYY-MM-DD'),
  '{{source_file}}',
  '{{checksum}}',
  ROW_NUMBER() OVER (
    ORDER BY FLIGHTDATE, REPORTING_AIRLINE, FLIGHT_NUMBER_REPORTING_AIRLINE,
             ORIGIN, DEST, CRSDEPTIME
  ),
  SHA2(CONCAT_WS('|',
    COALESCE(FLIGHTDATE, ''), COALESCE(REPORTING_AIRLINE, ''),
    COALESCE(FLIGHT_NUMBER_REPORTING_AIRLINE, ''), COALESCE(ORIGIN, ''),
    COALESCE(DEST, ''), COALESCE(CRSDEPTIME, ''), COALESCE(DEPTIME, ''),
    COALESCE(ARRTIME, ''), COALESCE(CANCELLED, ''), COALESCE(DIVERTED, ''),
    COALESCE(DISTANCE, '')
  ), 256),
  '{{run_id}}'
FROM BTS_MONTH_BUFFER;

COMMIT;
