CREATE OR REPLACE TABLE {{database}}.{{analytics_schema}}.MART_AIRLINE_PERFORMANCE AS
SELECT
  A.AIRLINE_CODE AS AIRLINE,
  COUNT(*) AS TOTAL_FLIGHTS,
  COUNT_IF(F.ON_TIME_FLAG) AS ON_TIME_FLIGHTS,
  COUNT_IF(NOT F.ON_TIME_FLAG AND NOT F.CANCELLED_FLAG AND NOT F.DIVERTED_FLAG) AS DELAYED_FLIGHTS,
  COUNT_IF(F.CANCELLED_FLAG) AS CANCELLED_FLIGHTS,
  ROUND(AVG(IFF(NOT F.CANCELLED_FLAG AND NOT F.DIVERTED_FLAG, F.ARRIVAL_DELAY_MINUTES, NULL)), 2) AS AVG_ARRIVAL_DELAY,
  ROUND(100.0 * COUNT_IF(F.ON_TIME_FLAG) / NULLIF(COUNT_IF(NOT F.CANCELLED_FLAG AND NOT F.DIVERTED_FLAG), 0), 2) AS ON_TIME_PERCENTAGE
FROM {{database}}.{{analytics_schema}}.FACT_FLIGHTS F
JOIN {{database}}.{{analytics_schema}}.DIM_AIRLINE A USING (AIRLINE_KEY)
GROUP BY A.AIRLINE_CODE;

CREATE OR REPLACE TABLE {{database}}.{{analytics_schema}}.MART_ROUTE_PERFORMANCE AS
SELECT
  O.AIRPORT_CODE AS ORIGIN,
  D.AIRPORT_CODE AS DESTINATION,
  COUNT(*) AS TOTAL_FLIGHTS,
  ROUND(AVG(IFF(NOT F.CANCELLED_FLAG AND NOT F.DIVERTED_FLAG, F.ARRIVAL_DELAY_MINUTES, NULL)), 2) AS AVG_DELAY,
  ROUND(100.0 * COUNT_IF(F.CANCELLED_FLAG) / NULLIF(COUNT(*), 0), 2) AS CANCELLATION_RATE,
  ROUND(AVG(F.ACTUAL_ELAPSED_MINUTES), 2) AS AVG_ELAPSED_TIME
FROM {{database}}.{{analytics_schema}}.FACT_FLIGHTS F
JOIN {{database}}.{{analytics_schema}}.DIM_AIRPORT O
  ON O.AIRPORT_KEY = F.ORIGIN_AIRPORT_KEY
JOIN {{database}}.{{analytics_schema}}.DIM_AIRPORT D
  ON D.AIRPORT_KEY = F.DESTINATION_AIRPORT_KEY
GROUP BY O.AIRPORT_CODE, D.AIRPORT_CODE;

CREATE OR REPLACE TABLE {{database}}.{{analytics_schema}}.MART_DELAY_CAUSES AS
SELECT
  A.AIRLINE_CODE AS AIRLINE,
  TO_CHAR(F.SOURCE_MONTH, 'YYYY-MM') AS YEAR_MONTH,
  SUM(COALESCE(F.CARRIER_DELAY_MINUTES, 0)) AS CARRIER_DELAY_MINUTES,
  SUM(COALESCE(F.WEATHER_DELAY_MINUTES, 0)) AS WEATHER_DELAY_MINUTES,
  SUM(COALESCE(F.NAS_DELAY_MINUTES, 0)) AS NAS_DELAY_MINUTES,
  SUM(COALESCE(F.SECURITY_DELAY_MINUTES, 0)) AS SECURITY_DELAY_MINUTES,
  SUM(COALESCE(F.LATE_AIRCRAFT_DELAY_MINUTES, 0)) AS LATE_AIRCRAFT_DELAY_MINUTES
FROM {{database}}.{{analytics_schema}}.FACT_FLIGHTS F
JOIN {{database}}.{{analytics_schema}}.DIM_AIRLINE A USING (AIRLINE_KEY)
GROUP BY A.AIRLINE_CODE, F.SOURCE_MONTH;

