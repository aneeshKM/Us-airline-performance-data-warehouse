BEGIN;

DELETE FROM {{database}}.{{staging_schema}}.FLIGHTS_CLEAN
WHERE SOURCE_MONTH = TO_DATE('{{source_month}}-01', 'YYYY-MM-DD');

INSERT INTO {{database}}.{{staging_schema}}.FLIGHTS_CLEAN (
  FLIGHT_ID, FLIGHT_DATE, SOURCE_MONTH, AIRLINE_CODE, AIRLINE_DOT_ID,
  FLIGHT_NUMBER, TAIL_NUMBER,
  ORIGIN_AIRPORT_ID, ORIGIN_CODE, ORIGIN_CITY, ORIGIN_STATE,
  DESTINATION_AIRPORT_ID, DESTINATION_CODE, DESTINATION_CITY, DESTINATION_STATE,
  SCHEDULED_DEPARTURE, ACTUAL_DEPARTURE, SCHEDULED_ARRIVAL, ACTUAL_ARRIVAL,
  DEPARTURE_DELAY_MINUTES, ARRIVAL_DELAY_MINUTES,
  SCHEDULED_ELAPSED_MINUTES, ACTUAL_ELAPSED_MINUTES, AIR_TIME_MINUTES,
  DISTANCE_MILES, CANCELLED_FLAG, CANCELLATION_CODE, DIVERTED_FLAG,
  ON_TIME_FLAG, DELAY_CATEGORY,
  CARRIER_DELAY_MINUTES, WEATHER_DELAY_MINUTES, NAS_DELAY_MINUTES,
  SECURITY_DELAY_MINUTES, LATE_AIRCRAFT_DELAY_MINUTES,
  SOURCE_FILE, SOURCE_RECORD_HASH, PIPELINE_RUN_ID
)
WITH TYPED AS (
  SELECT
    TRY_TO_DATE(FLIGHTDATE, 'YYYY-MM-DD') AS FLIGHT_DATE,
    SOURCE_MONTH,
    NULLIF(TRIM(REPORTING_AIRLINE), '') AS AIRLINE_CODE,
    TRY_TO_NUMBER(DOT_ID_REPORTING_AIRLINE) AS AIRLINE_DOT_ID,
    NULLIF(TRIM(FLIGHT_NUMBER_REPORTING_AIRLINE), '') AS FLIGHT_NUMBER,
    NULLIF(TRIM(TAIL_NUMBER), '') AS TAIL_NUMBER,
    TRY_TO_NUMBER(ORIGINAIRPORTID) AS ORIGIN_AIRPORT_ID,
    NULLIF(TRIM(ORIGIN), '') AS ORIGIN_CODE,
    NULLIF(TRIM(ORIGINCITYNAME), '') AS ORIGIN_CITY,
    NULLIF(TRIM(ORIGINSTATE), '') AS ORIGIN_STATE,
    TRY_TO_NUMBER(DESTAIRPORTID) AS DESTINATION_AIRPORT_ID,
    NULLIF(TRIM(DEST), '') AS DESTINATION_CODE,
    NULLIF(TRIM(DESTCITYNAME), '') AS DESTINATION_CITY,
    NULLIF(TRIM(DESTSTATE), '') AS DESTINATION_STATE,
    TRY_TO_TIME(IFF(LPAD(CRSDEPTIME, 4, '0') = '2400', '0000', LPAD(CRSDEPTIME, 4, '0')), 'HH24MI') AS SCHEDULED_DEPARTURE,
    TRY_TO_TIME(IFF(LPAD(DEPTIME, 4, '0') = '2400', '0000', LPAD(DEPTIME, 4, '0')), 'HH24MI') AS ACTUAL_DEPARTURE,
    TRY_TO_TIME(IFF(LPAD(CRSARRTIME, 4, '0') = '2400', '0000', LPAD(CRSARRTIME, 4, '0')), 'HH24MI') AS SCHEDULED_ARRIVAL,
    TRY_TO_TIME(IFF(LPAD(ARRTIME, 4, '0') = '2400', '0000', LPAD(ARRTIME, 4, '0')), 'HH24MI') AS ACTUAL_ARRIVAL,
    TRY_TO_DECIMAL(DEPDELAY, 10, 2) AS DEPARTURE_DELAY_MINUTES,
    TRY_TO_DECIMAL(ARRDELAY, 10, 2) AS ARRIVAL_DELAY_MINUTES,
    TRY_TO_DECIMAL(CRSELAPSEDTIME, 10, 2) AS SCHEDULED_ELAPSED_MINUTES,
    TRY_TO_DECIMAL(ACTUALELAPSEDTIME, 10, 2) AS ACTUAL_ELAPSED_MINUTES,
    TRY_TO_DECIMAL(AIRTIME, 10, 2) AS AIR_TIME_MINUTES,
    TRY_TO_DECIMAL(DISTANCE, 10, 2) AS DISTANCE_MILES,
    COALESCE(TRY_TO_NUMBER(CANCELLED) = 1, FALSE) AS CANCELLED_FLAG,
    NULLIF(TRIM(CANCELLATIONCODE), '') AS CANCELLATION_CODE,
    COALESCE(TRY_TO_NUMBER(DIVERTED) = 1, FALSE) AS DIVERTED_FLAG,
    TRY_TO_DECIMAL(CARRIERDELAY, 10, 2) AS CARRIER_DELAY_MINUTES,
    TRY_TO_DECIMAL(WEATHERDELAY, 10, 2) AS WEATHER_DELAY_MINUTES,
    TRY_TO_DECIMAL(NASDELAY, 10, 2) AS NAS_DELAY_MINUTES,
    TRY_TO_DECIMAL(SECURITYDELAY, 10, 2) AS SECURITY_DELAY_MINUTES,
    TRY_TO_DECIMAL(LATEAIRCRAFTDELAY, 10, 2) AS LATE_AIRCRAFT_DELAY_MINUTES,
    SOURCE_FILE,
    SOURCE_ROW_NUMBER,
    SOURCE_RECORD_HASH,
    PIPELINE_RUN_ID,
    LOADED_AT
  FROM {{database}}.{{raw_schema}}.FLIGHTS
  WHERE SOURCE_MONTH = TO_DATE('{{source_month}}-01', 'YYYY-MM-DD')
), VALID AS (
  SELECT *,
    SHA2(CONCAT_WS('|', FLIGHT_DATE::VARCHAR, AIRLINE_CODE, FLIGHT_NUMBER,
      ORIGIN_CODE, DESTINATION_CODE, COALESCE(SCHEDULED_DEPARTURE::VARCHAR, '')), 256) AS FLIGHT_ID
  FROM TYPED
  WHERE FLIGHT_DATE IS NOT NULL
    AND DATE_TRUNC('MONTH', FLIGHT_DATE) = TO_DATE('{{source_month}}-01', 'YYYY-MM-DD')
    AND AIRLINE_CODE IS NOT NULL
    AND FLIGHT_NUMBER IS NOT NULL
    AND ORIGIN_AIRPORT_ID IS NOT NULL
    AND ORIGIN_CODE IS NOT NULL
    AND DESTINATION_AIRPORT_ID IS NOT NULL
    AND DESTINATION_CODE IS NOT NULL
    AND DISTANCE_MILES > 0
    AND DISTANCE_MILES <= 10000
  QUALIFY ROW_NUMBER() OVER (
    PARTITION BY FLIGHT_DATE, AIRLINE_CODE, FLIGHT_NUMBER,
                 ORIGIN_CODE, DESTINATION_CODE, SCHEDULED_DEPARTURE
    ORDER BY LOADED_AT DESC, SOURCE_RECORD_HASH DESC, SOURCE_ROW_NUMBER DESC
  ) = 1
)
SELECT
  FLIGHT_ID, FLIGHT_DATE, SOURCE_MONTH, AIRLINE_CODE, AIRLINE_DOT_ID,
  FLIGHT_NUMBER, TAIL_NUMBER,
  ORIGIN_AIRPORT_ID, ORIGIN_CODE, ORIGIN_CITY, ORIGIN_STATE,
  DESTINATION_AIRPORT_ID, DESTINATION_CODE, DESTINATION_CITY, DESTINATION_STATE,
  SCHEDULED_DEPARTURE, ACTUAL_DEPARTURE, SCHEDULED_ARRIVAL, ACTUAL_ARRIVAL,
  DEPARTURE_DELAY_MINUTES, ARRIVAL_DELAY_MINUTES,
  SCHEDULED_ELAPSED_MINUTES, ACTUAL_ELAPSED_MINUTES, AIR_TIME_MINUTES,
  DISTANCE_MILES, CANCELLED_FLAG, CANCELLATION_CODE, DIVERTED_FLAG,
  COALESCE(
    NOT CANCELLED_FLAG AND NOT DIVERTED_FLAG AND ARRIVAL_DELAY_MINUTES <= 15,
    FALSE
  ) AS ON_TIME_FLAG,
  CASE
    WHEN CANCELLED_FLAG THEN 'CANCELLED'
    WHEN DIVERTED_FLAG THEN 'DIVERTED'
    WHEN ARRIVAL_DELAY_MINUTES IS NULL THEN 'UNKNOWN'
    WHEN ARRIVAL_DELAY_MINUTES <= 15 THEN 'ON_TIME'
    WHEN ARRIVAL_DELAY_MINUTES <= 60 THEN 'MODERATE_DELAY'
    ELSE 'SEVERE_DELAY'
  END AS DELAY_CATEGORY,
  CARRIER_DELAY_MINUTES, WEATHER_DELAY_MINUTES, NAS_DELAY_MINUTES,
  SECURITY_DELAY_MINUTES, LATE_AIRCRAFT_DELAY_MINUTES,
  SOURCE_FILE, SOURCE_RECORD_HASH, PIPELINE_RUN_ID
FROM VALID;

COMMIT;
