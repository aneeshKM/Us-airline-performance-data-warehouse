-- One-time account bootstrap. Run as ACCOUNTADMIN in a Snowflake worksheet.
-- The final GRANT assigns the least-privilege project role to the user running this script.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS AIRLINE_ETL_ROLE
  COMMENT = 'Runs the US Airline Performance Data Warehouse pipeline';

CREATE WAREHOUSE IF NOT EXISTS AIRLINE_ETL_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  COMMENT = 'Cost-controlled warehouse for monthly BTS ingestion';

CREATE DATABASE IF NOT EXISTS AIRLINE_PERFORMANCE
  COMMENT = 'BTS reporting-carrier on-time performance warehouse';

GRANT USAGE, OPERATE ON WAREHOUSE AIRLINE_ETL_WH TO ROLE AIRLINE_ETL_ROLE;
GRANT USAGE ON DATABASE AIRLINE_PERFORMANCE TO ROLE AIRLINE_ETL_ROLE;
GRANT CREATE SCHEMA ON DATABASE AIRLINE_PERFORMANCE TO ROLE AIRLINE_ETL_ROLE;
SET PROJECT_USER = CURRENT_USER();
GRANT ROLE AIRLINE_ETL_ROLE TO USER IDENTIFIER($PROJECT_USER);

-- Then configure .env and run: airline-warehouse init
