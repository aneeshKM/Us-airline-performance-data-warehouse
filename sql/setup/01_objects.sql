CREATE FILE FORMAT IF NOT EXISTS {{raw_schema}}.BTS_CSV_WITH_HEADER
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NA', 'N/A', 'NULL')
  EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  ENCODING = 'UTF8';

CREATE STAGE IF NOT EXISTS {{raw_schema}}.{{stage}}
  FILE_FORMAT = (FORMAT_NAME = '{{database}}.{{raw_schema}}.BTS_CSV_WITH_HEADER')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Internal stage partitioned by source month and file checksum';

