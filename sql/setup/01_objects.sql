CREATE OR REPLACE VIEW {{metadata_schema}}.LATEST_SUCCESSFUL_MONTHS AS
SELECT SOURCE_MONTH, SOURCE_FILE, SOURCE_FILE_CHECKSUM, RECORDS_LOADED,
       LOADED_AT, PIPELINE_RUN_ID
FROM {{metadata_schema}}.PIPELINE_LOADS
WHERE STATUS = 'SUCCESS'
QUALIFY ROW_NUMBER() OVER (PARTITION BY SOURCE_MONTH ORDER BY LOADED_AT DESC) = 1;
